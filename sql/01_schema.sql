-- 01_schema.sql
-- Схема базы данных ИС «Сходим» (22 таблицы)
-- Использование: psql -d skhodim_course -v app_schema=skhodim -f 01_schema.sql

\set ON_ERROR_STOP on

-- На helios личная схема уже есть, а CREATE на базе studs запрещён.
SELECT format('CREATE SCHEMA %I', :'app_schema')
WHERE NOT EXISTS (
    SELECT 1 FROM pg_namespace WHERE nspname = :'app_schema'
)\gexec

SET search_path TO :app_schema, public;

-- ==========================================
-- 1. Учётные записи и профиль
-- ==========================================

CREATE TABLE app_user (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           varchar(254) NOT NULL,
    password_hash   varchar(100) NOT NULL,
    role            varchar(16)  NOT NULL DEFAULT 'USER'
                    CHECK (role IN ('USER', 'MODERATOR')),
    is_banned       boolean      NOT NULL DEFAULT false,
    created_at      timestamptz  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uq_app_user_email_lower ON app_user (lower(email));

CREATE TABLE user_profile (
    user_id     bigint PRIMARY KEY REFERENCES app_user(id) ON DELETE CASCADE,
    nickname    varchar(40)  NOT NULL,
    avatar_key  varchar(500),
    metro       varchar(100)
);

CREATE TABLE user_interest (
    user_id      bigint NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    category_id  bigint NOT NULL,  -- FK added after category
    PRIMARY KEY (user_id, category_id)
);

-- ==========================================
-- 2. Справочники и каталог
-- ==========================================

CREATE TABLE catalog_source (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     varchar(40)  NOT NULL UNIQUE,
    name     varchar(100) NOT NULL,
    base_url text         NOT NULL
);

CREATE TABLE category (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug  varchar(80)  NOT NULL UNIQUE,
    name  varchar(100) NOT NULL
);

ALTER TABLE user_interest
    ADD CONSTRAINT fk_user_interest_category
    FOREIGN KEY (category_id) REFERENCES category(id) ON DELETE CASCADE;

CREATE TABLE tag (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  varchar(100) NOT NULL UNIQUE
);

CREATE TABLE place (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id    bigint       NOT NULL REFERENCES catalog_source(id),
    external_id  varchar(100) NOT NULL,
    name         varchar(255) NOT NULL,
    address      text,
    metro        varchar(100),
    latitude     numeric(9,6) CHECK (latitude IS NULL OR (latitude >= -90 AND latitude <= 90)),
    longitude    numeric(9,6) CHECK (longitude IS NULL OR (longitude >= -180 AND longitude <= 180)),
    UNIQUE (source_id, external_id),
    CHECK ((latitude IS NULL) = (longitude IS NULL))
);

CREATE TABLE event (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id      bigint       NOT NULL REFERENCES catalog_source(id),
    external_id    varchar(100) NOT NULL,
    place_id       bigint REFERENCES place(id),
    title          varchar(300) NOT NULL,
    description    text         NOT NULL,
    age_limit      smallint     CHECK (age_limit IS NULL OR (age_limit >= 0 AND age_limit <= 21)),
    is_free        boolean,
    price_from     numeric(12,2) CHECK (price_from IS NULL OR price_from >= 0),
    price_text     text,
    cover_url      text,
    source_url     text         NOT NULL,
    ticket_url     text,
    published      boolean      NOT NULL,
    hidden_at      timestamptz,
    imported_at    timestamptz  NOT NULL DEFAULT now(),
    search_vector  tsvector GENERATED ALWAYS AS (
                       setweight(to_tsvector('russian', coalesce(title, '')), 'A') ||
                       setweight(to_tsvector('russian', coalesce(description, '')), 'B')
                   ) STORED,
    UNIQUE (source_id, external_id)
);

CREATE TABLE event_session (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     bigint       NOT NULL REFERENCES event(id) ON DELETE CASCADE,
    source_key   varchar(160) NOT NULL,
    starts_at    timestamptz  NOT NULL,
    ends_at      timestamptz,
    cancelled_at timestamptz,
    UNIQUE (event_id, source_key),
    CHECK (ends_at IS NULL OR ends_at > starts_at)
);

CREATE TABLE event_category (
    event_id     bigint NOT NULL REFERENCES event(id) ON DELETE CASCADE,
    category_id  bigint NOT NULL REFERENCES category(id) ON DELETE CASCADE,
    PRIMARY KEY (event_id, category_id)
);

CREATE TABLE event_tag (
    event_id  bigint NOT NULL REFERENCES event(id) ON DELETE CASCADE,
    tag_id    bigint NOT NULL REFERENCES tag(id) ON DELETE CASCADE,
    PRIMARY KEY (event_id, tag_id)
);

-- ==========================================
-- 3. Действия, намерения и общение
-- ==========================================

CREATE TABLE event_reaction (
    user_id     bigint      NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    event_id    bigint      NOT NULL REFERENCES event(id) ON DELETE CASCADE,
    kind        varchar(4)  NOT NULL CHECK (kind IN ('LIKE', 'SKIP')),
    is_public   boolean     NOT NULL DEFAULT false,
    reacted_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, event_id),
    CHECK (kind = 'LIKE' OR is_public = false)
);

CREATE TABLE event_intention (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    session_id  bigint      NOT NULL REFERENCES event_session(id) ON DELETE CASCADE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, session_id)
);

CREATE TABLE intention_period (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intention_id  bigint      NOT NULL REFERENCES event_intention(id) ON DELETE CASCADE,
    started_at    timestamptz NOT NULL,
    ended_at      timestamptz,
    CHECK (ended_at IS NULL OR ended_at > started_at)
);

CREATE UNIQUE INDEX uq_intention_open
    ON intention_period (intention_id)
    WHERE ended_at IS NULL;

CREATE TABLE companion_request (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   bigint      NOT NULL REFERENCES event_session(id),
    sender_id    bigint      NOT NULL REFERENCES app_user(id),
    receiver_id  bigint      NOT NULL REFERENCES app_user(id),
    user_low     bigint GENERATED ALWAYS AS (least(sender_id, receiver_id)) STORED,
    user_high    bigint GENERATED ALWAYS AS (greatest(sender_id, receiver_id)) STORED,
    status       varchar(12) NOT NULL
                 CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED')),
    created_at   timestamptz NOT NULL DEFAULT now(),
    resolved_at  timestamptz,
    CHECK (sender_id <> receiver_id),
    UNIQUE (session_id, user_low, user_high),
    CHECK (
        (status = 'PENDING' AND resolved_at IS NULL) OR
        (status <> 'PENDING' AND resolved_at IS NOT NULL)
    )
);

CREATE TABLE conversation (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  bigint      NOT NULL UNIQUE REFERENCES companion_request(id),
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE message (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  bigint       NOT NULL REFERENCES conversation(id) ON DELETE CASCADE,
    author_id        bigint       NOT NULL REFERENCES app_user(id),
    body             varchar(2000) NOT NULL,
    created_at       timestamptz  NOT NULL DEFAULT now(),
    CHECK (length(trim(body)) BETWEEN 1 AND 2000)
);

-- ==========================================
-- 4. Обратная связь и сопровождение
-- ==========================================

CREATE TABLE event_feedback (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    bigint       NOT NULL REFERENCES event(id),
    session_id  bigint       REFERENCES event_session(id),
    author_id   bigint       NOT NULL REFERENCES app_user(id),
    body        varchar(2000) NOT NULL,
    rating      smallint     CHECK (rating IS NULL OR (rating >= 1 AND rating <= 5)),
    created_at  timestamptz  NOT NULL DEFAULT now(),
    hidden_at   timestamptz,
    deleted_at  timestamptz,
    CHECK (length(trim(body)) BETWEEN 1 AND 2000),
    CHECK (
        (rating IS NULL AND session_id IS NULL) OR
        (rating IS NOT NULL AND session_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_feedback_review
    ON event_feedback (author_id, event_id)
    WHERE rating IS NOT NULL;

CREATE TABLE notification (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    kind        varchar(20) NOT NULL
                CHECK (kind IN ('REQUEST', 'ACCEPTED', 'REJECTED', 'MESSAGE')),
    request_id  bigint REFERENCES companion_request(id),
    message_id  bigint REFERENCES message(id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    read_at     timestamptz,
    CHECK (
        (kind IN ('REQUEST', 'ACCEPTED', 'REJECTED') AND request_id IS NOT NULL AND message_id IS NULL) OR
        (kind = 'MESSAGE' AND message_id IS NOT NULL AND request_id IS NULL)
    )
);

CREATE TABLE report (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id    bigint       NOT NULL REFERENCES app_user(id),
    target_type  varchar(20)  NOT NULL
                 CHECK (target_type IN ('event', 'user', 'feedback')),
    target_id    bigint       NOT NULL,
    reason       varchar(1000) NOT NULL,
    status       varchar(10)  NOT NULL DEFAULT 'NEW'
                 CHECK (status IN ('NEW', 'REVIEWED')),
    created_at   timestamptz  NOT NULL DEFAULT now(),
    reviewed_at  timestamptz,
    CHECK (
        (status = 'NEW' AND reviewed_at IS NULL) OR
        (status = 'REVIEWED' AND reviewed_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_report_open
    ON report (author_id, target_type, target_id)
    WHERE status = 'NEW';

-- ==========================================
-- 5. Импорт
-- ==========================================

CREATE TABLE import_run (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id        bigint      NOT NULL REFERENCES catalog_source(id),
    status           varchar(10) NOT NULL
                     CHECK (status IN ('RUNNING', 'SUCCESS', 'PARTIAL', 'FAILED')),
    started_at       timestamptz NOT NULL,
    finished_at      timestamptz,
    processed_count  integer     NOT NULL DEFAULT 0,
    error_count      integer     NOT NULL DEFAULT 0,
    CHECK (
        (status = 'RUNNING' AND finished_at IS NULL) OR
        (status <> 'RUNNING' AND finished_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_import_running
    ON import_run (source_id)
    WHERE status = 'RUNNING';

CREATE TABLE import_error (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id       bigint       NOT NULL REFERENCES import_run(id) ON DELETE CASCADE,
    external_id  varchar(100),
    error_code   varchar(80)  NOT NULL,
    detail       text         NOT NULL,
    created_at   timestamptz  NOT NULL DEFAULT now()
);

-- Права: отозвать PUBLIC
REVOKE ALL ON SCHEMA :app_schema FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA :app_schema FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA :app_schema FROM PUBLIC;
