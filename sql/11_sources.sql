-- 11_sources.sql
-- Этап 4: несколько источников афиши и склейка дублей.
-- Скрипт только добавляет объекты и переносит данные в новую таблицу, его можно запускать повторно.
--
-- Одно событие может прийти из нескольких источников (Кассир.ру, Афиша.ру, KudaGo).
-- event_link хранит данные каждого источника, а поля event собираются из них функцией refresh_event.
-- find_duplicate_pairs ищет пары дублей, resolve_duplicates уверенные склеивает, сомнительные
-- отдаёт модератору через event_duplicate. merge_events переносит на оставшееся событие
-- сеансы, лайки, комментарии и жалобы, ничего из действий пользователей не теряя.

\set ON_ERROR_STOP on
SET search_path TO :app_schema, public;

-- Чем выше, тем лучше постеры источника: при склейке событие берёт постер оттуда.
ALTER TABLE catalog_source ADD COLUMN IF NOT EXISTS media_rank smallint NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS event_link (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     bigint        NOT NULL REFERENCES event(id) ON DELETE CASCADE,
    source_id    bigint        NOT NULL REFERENCES catalog_source(id),
    external_id  varchar(100)  NOT NULL,
    title        varchar(300)  NOT NULL,
    description  text,
    cover_url    text,
    is_free      boolean,
    price_from   numeric(12,2) CHECK (price_from IS NULL OR price_from >= 0),
    price_text   text,
    age_limit    smallint      CHECK (age_limit IS NULL OR (age_limit >= 0 AND age_limit <= 21)),
    source_url   text          NOT NULL,
    ticket_url   text,
    imported_at  timestamptz   NOT NULL DEFAULT now(),
    UNIQUE (source_id, external_id)
);

CREATE INDEX IF NOT EXISTS ix_event_link_event ON event_link (event_id);

-- Каждое уже загруженное событие становится своим первым источником.
INSERT INTO event_link (
    event_id, source_id, external_id, title, description, cover_url, is_free,
    price_from, price_text, age_limit, source_url, ticket_url, imported_at
)
SELECT id, source_id, external_id, title, description, cover_url, is_free,
       price_from, price_text, age_limit, source_url, ticket_url, imported_at
FROM event
ON CONFLICT (source_id, external_id) DO NOTHING;

-- Пары возможных дублей и история склеек. Внешних ключей на event нет намеренно:
-- склеенное событие удаляется, а запись о склейке остаётся в истории.
CREATE TABLE IF NOT EXISTS event_duplicate (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_a      bigint        NOT NULL,
    event_b      bigint        NOT NULL,
    title_a      varchar(300)  NOT NULL,
    title_b      varchar(300)  NOT NULL,
    score        numeric(4,2)  NOT NULL,
    reason       text          NOT NULL,
    status       varchar(10)   NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'MERGED', 'DISTINCT')),
    created_at   timestamptz   NOT NULL DEFAULT now(),
    resolved_at  timestamptz,
    resolved_by  bigint        REFERENCES app_user(id),
    CHECK (event_a < event_b),
    CHECK ((status = 'NEW') = (resolved_at IS NULL)),
    UNIQUE (event_a, event_b)
);

CREATE INDEX IF NOT EXISTS ix_event_duplicate_new ON event_duplicate (status) WHERE status = 'NEW';
CREATE INDEX IF NOT EXISTS ix_event_session_starts ON event_session (starts_at);

-- ==========================================
-- Нормализация названий и площадок
-- ==========================================

-- Регистр приводится вручную: lower() для кириллицы зависит от локали базы, а она на серверах разная.
CREATE OR REPLACE FUNCTION norm_text(p text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
    SELECT btrim(regexp_replace(
        lower(translate(coalesce(p, ''),
            'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯё',
            'абвгдеежзийклмнопрстуфхцчшщъыьэюяе')),
        '[^0-9a-zа-я]+', ' ', 'g'))
$$;

-- Слова названия без служебных и без пометок в скобках: «Лолита (ЛОЖИ)» и «Лолита.» дают одно и то же.
-- Жанр в названии тоже не различает события: «Группа «ПЕЛАГЕЯ»» у Кассира это «Пелагея» у Афиши.ру.
CREATE OR REPLACE FUNCTION title_tokens(p text) RETURNS text[]
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
    SELECT coalesce(array_agg(DISTINCT w ORDER BY w), '{}')
    FROM unnest(string_to_array(norm_text(regexp_replace(coalesce(p, ''), '\([^)]*\)', ' ', 'g')), ' ')) AS w
    WHERE w <> ''
      AND NOT w = ANY ('{и,в,во,на,с,со,по,для,от,до,из,к,о,об,а,the,of,and,премьера,петербурге,петербург,санкт,билеты,билет,входные,группа,мюзикл,спектакль,концерт,комедия,драма,трагедия,представление}'::text[])
$$;

-- Слова названия площадки. Тип площадки («театр», «ДК», «СК») остаётся: без него
-- «ДК Ленсовета» совпал бы с «Театром им. Ленсовета».
CREATE OR REPLACE FUNCTION place_tokens(p text) RETURNS text[]
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
    SELECT coalesce(array_agg(DISTINCT w ORDER BY w), '{}')
    FROM unnest(string_to_array(norm_text(p), ' ')) AS w
    WHERE length(w) > 1
      AND NOT w = ANY ('{санкт,петербургский,петербургская,петербург,спб,им,имени,неизвестно,г}'::text[])
$$;

-- Доля слов меньшего набора, которые есть в большем. NULL, если один из наборов пуст.
CREATE OR REPLACE FUNCTION token_containment(a text[], b text[]) RETURNS numeric
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
    SELECT CASE WHEN cardinality(a) = 0 OR cardinality(b) = 0 THEN NULL
                ELSE round((SELECT count(*) FROM unnest(a) x WHERE x = ANY (b))::numeric
                           / least(cardinality(a), cardinality(b)), 2) END
$$;

-- Пересечение к объединению.
CREATE OR REPLACE FUNCTION token_jaccard(a text[], b text[]) RETURNS numeric
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
    SELECT CASE WHEN cardinality(a) = 0 OR cardinality(b) = 0 THEN NULL
                ELSE round(i::numeric / (cardinality(a) + cardinality(b) - i), 2) END
    FROM (SELECT count(*) AS i FROM unnest(a) x WHERE x = ANY (b)) AS c
$$;

-- Площадка другого источника с теми же словами в названии: «СК «Юбилейный»» и «СК Юбилейный».
CREATE OR REPLACE FUNCTION find_place_alias(p_name text) RETURNS bigint
LANGUAGE sql STABLE
AS $$
    SELECT p.id
    FROM place p
    WHERE cardinality(place_tokens(p_name)) > 0
      AND place_tokens(p.name) = place_tokens(p_name)
    ORDER BY p.id
    LIMIT 1
$$;

-- ==========================================
-- Данные события из его источников
-- ==========================================

-- Ссылки и место берутся у основного источника, остальное у лучшего: минимальная цена,
-- настоящее описание, название и постер у источника с лучшими данными (media_rank).
CREATE OR REPLACE FUNCTION refresh_event(p_event bigint) RETURNS void
LANGUAGE plpgsql
SET search_path FROM CURRENT
AS $$
DECLARE
    prim event_link%ROWTYPE;
    cheapest event_link%ROWTYPE;
    best_description text;
    best_cover text;
    best_title varchar;
    any_free boolean;
    max_age smallint;
BEGIN
    SELECT l.* INTO prim
    FROM event_link l
    JOIN event e ON e.id = l.event_id AND e.source_id = l.source_id AND e.external_id = l.external_id
    WHERE l.event_id = p_event;
    IF NOT FOUND THEN
        SELECT * INTO prim FROM event_link WHERE event_id = p_event ORDER BY id LIMIT 1;
        IF NOT FOUND THEN
            RETURN;
        END IF;
    END IF;

    SELECT * INTO cheapest
    FROM event_link
    WHERE event_id = p_event AND price_from IS NOT NULL
    ORDER BY price_from, id
    LIMIT 1;

    SELECT description INTO best_description
    FROM event_link
    WHERE event_id = p_event
      AND description IS NOT NULL
      AND norm_text(description) <> norm_text(title)
    ORDER BY length(description) DESC, id
    LIMIT 1;

    SELECT l.cover_url INTO best_cover
    FROM event_link l
    JOIN catalog_source cs ON cs.id = l.source_id
    WHERE l.event_id = p_event AND l.cover_url IS NOT NULL
    ORDER BY cs.media_rank DESC, (l.id = prim.id) DESC, l.id
    LIMIT 1;

    -- У Кассира названия часто набраны капсом («ХАСКИ»), у Афиши.ру аккуратнее: берётся лучший источник.
    SELECT l.title INTO best_title
    FROM event_link l
    JOIN catalog_source cs ON cs.id = l.source_id
    WHERE l.event_id = p_event
    ORDER BY cs.media_rank DESC, (l.id = prim.id) DESC, l.id
    LIMIT 1;

    SELECT bool_or(is_free), max(age_limit) INTO any_free, max_age
    FROM event_link WHERE event_id = p_event;

    UPDATE event
    SET title = coalesce(best_title, prim.title),
        -- Без настоящего описания остаётся название: интерфейс такое описание не показывает.
        description = coalesce(best_description, best_title, prim.title),
        cover_url = coalesce(best_cover, prim.cover_url),
        price_from = cheapest.price_from,
        price_text = coalesce(cheapest.price_text, prim.price_text),
        is_free = CASE WHEN cheapest.price_from = 0 THEN true
                       WHEN cheapest.price_from > 0 THEN false
                       ELSE any_free END,
        age_limit = max_age,
        source_url = prim.source_url,
        ticket_url = prim.ticket_url,
        imported_at = now()
    WHERE id = p_event;
END;
$$;

-- Сеанс, который другой источник уже привёз на то же время, повторно не создаётся.
CREATE OR REPLACE FUNCTION upsert_event_session(
    p_event bigint, p_key varchar, p_starts timestamptz, p_ends timestamptz
) RETURNS void
LANGUAGE plpgsql
SET search_path FROM CURRENT
AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM event_session WHERE event_id = p_event AND source_key = p_key) THEN
        UPDATE event_session
        SET starts_at = p_starts, ends_at = p_ends
        WHERE event_id = p_event AND source_key = p_key
          AND (starts_at, ends_at) IS DISTINCT FROM (p_starts, p_ends);
        RETURN;
    END IF;
    IF EXISTS (
        SELECT 1 FROM event_session
        WHERE event_id = p_event
          AND abs(extract(epoch FROM starts_at - p_starts)) <= 300
    ) THEN
        RETURN;
    END IF;
    INSERT INTO event_session (event_id, source_key, starts_at, ends_at)
    VALUES (p_event, p_key, p_starts, p_ends);
END;
$$;

-- Где купить: все источники события, самые дешёвые первыми.
CREATE OR REPLACE FUNCTION event_offers(p_event bigint)
RETURNS TABLE (source_code varchar, source_name varchar, url text, price_from numeric, price_text text)
LANGUAGE sql STABLE
AS $$
    SELECT cs.code, cs.name, coalesce(l.ticket_url, l.source_url), l.price_from, l.price_text
    FROM event_link l
    JOIN catalog_source cs ON cs.id = l.source_id
    WHERE l.event_id = p_event
    ORDER BY l.price_from NULLS LAST, l.id
$$;

-- ==========================================
-- Поиск и склейка дублей
-- ==========================================

-- Пары событий, которые идут в один день и похожи по названию и площадке.
-- confident: склеивается автоматически; иначе пару смотрит модератор.
CREATE OR REPLACE FUNCTION find_duplicate_pairs()
RETURNS TABLE (event_a bigint, event_b bigint, score numeric, confident boolean, reason text)
LANGUAGE sql STABLE
AS $$
    WITH s AS (
        SELECT es.event_id, es.starts_at, (es.starts_at AT TIME ZONE 'Europe/Moscow')::date AS day
        FROM event_session es
        JOIN event e ON e.id = es.event_id
        WHERE e.hidden_at IS NULL
          AND es.cancelled_at IS NULL
          AND coalesce(es.ends_at, es.starts_at) > now()
    ),
    pairs AS (
        SELECT s1.event_id AS a, s2.event_id AS b,
               bool_or(abs(extract(epoch FROM s1.starts_at - s2.starts_at)) <= 1800) AS close
        FROM s s1
        JOIN s s2 ON s2.day = s1.day AND s1.event_id < s2.event_id
        GROUP BY 1, 2
    ),
    ev AS (
        SELECT e.id, e.source_id, e.place_id, title_tokens(e.title) AS tt, place_tokens(p.name) AS pt
        FROM event e
        LEFT JOIN place p ON p.id = e.place_id
        WHERE e.id IN (SELECT a FROM pairs UNION SELECT b FROM pairs)
    ),
    scored AS (
        SELECT p.a, p.b, p.close,
               ea.source_id = eb.source_id AS same_source,
               ea.tt = eb.tt AND cardinality(ea.tt) > 0 AS same_title,
               token_containment(ea.tt, eb.tt) AS tc,
               token_jaccard(ea.tt, eb.tt) AS tj,
               -- NULL: у одной из сторон площадка неизвестна.
               CASE WHEN ea.place_id = eb.place_id THEN 1
                    WHEN cardinality(ea.pt) = 0 OR cardinality(eb.pt) = 0 THEN NULL
                    ELSE coalesce(token_containment(ea.pt, eb.pt), 0) END AS pl
        FROM pairs p
        JOIN ev ea ON ea.id = p.a
        JOIN ev eb ON eb.id = p.b
    ),
    -- Площадка должна совпасть целиком: «Стендап по-Женски» в один вечер идёт в разных барах.
    -- Похожесть названий для автосклейки высокая: «Два мастер-класса» и «Комбо: экскурсия +
    -- два мастер-класса» это разные билеты. Внутри одного источника похожие названия чаще всего
    -- намеренно разные позиции (комбо, фан-зона), поэтому такие пары модератору не показываются.
    decided AS (
        SELECT a, b, round(0.6 * coalesce(tc, 0) + 0.4 * coalesce(pl, 0.5), 2) AS score,
               (close AND same_title AND coalesce(pl, 1) >= 0.8)
                   OR (close AND tc = 1 AND tj >= 0.6 AND pl >= 0.8)
                   OR (NOT close AND same_title AND pl >= 0.8) AS confident,
               NOT same_source AND (
                   (close AND tc >= 0.6 AND tj >= 0.4 AND coalesce(pl, 1) >= 0.8)
                   OR (NOT close AND same_title AND coalesce(pl, 1) >= 0.8)) AS candidate,
               format('название %s%%, площадка %s, %s',
                      round(100 * coalesce(tc, 0)),
                      CASE WHEN pl IS NULL THEN 'неизвестна' ELSE round(100 * pl) || '%' END,
                      CASE WHEN close THEN 'то же время' ELSE 'тот же день' END) AS reason
        FROM scored
    )
    SELECT d.a, d.b, d.score, d.confident, d.reason
    FROM decided d
    WHERE (d.confident OR d.candidate)
      AND NOT EXISTS (
          SELECT 1 FROM event_duplicate x
          WHERE x.event_a = d.a AND x.event_b = d.b AND x.status = 'DISTINCT'
      )
$$;

-- Пользователь уже что-то сделал с сеансом: такой сеанс при склейке не удаляется.
CREATE OR REPLACE FUNCTION session_has_activity(p_session bigint) RETURNS boolean
LANGUAGE sql STABLE
AS $$
    SELECT EXISTS (SELECT 1 FROM event_intention WHERE session_id = p_session)
        OR EXISTS (SELECT 1 FROM companion_request WHERE session_id = p_session)
        OR EXISTS (SELECT 1 FROM event_feedback WHERE session_id = p_session)
$$;

-- Переносит всё с p_drop на p_keep и удаляет p_drop. Отзывы с оценкой привязаны к расписанию,
-- поэтому событие с такими отзывами не склеивается.
CREATE OR REPLACE FUNCTION merge_events(p_keep bigint, p_drop bigint, p_by bigint, p_reason text)
RETURNS void
LANGUAGE plpgsql
SET search_path FROM CURRENT
AS $$
DECLARE
    title_keep varchar;
    title_drop varchar;
BEGIN
    IF p_keep = p_drop THEN
        RAISE EXCEPTION 'Cannot merge an event with itself';
    END IF;
    PERFORM 1 FROM event WHERE id IN (p_keep, p_drop) ORDER BY id FOR UPDATE;
    SELECT title INTO title_keep FROM event WHERE id = p_keep;
    SELECT title INTO title_drop FROM event WHERE id = p_drop;
    IF title_keep IS NULL OR title_drop IS NULL THEN
        RAISE EXCEPTION 'Event not found for merge';
    END IF;
    IF EXISTS (
        SELECT 1 FROM event_feedback f
        JOIN event_session s ON s.id = f.session_id
        WHERE s.event_id = p_drop AND f.rating IS NOT NULL
    ) THEN
        RAISE EXCEPTION 'Merged event has reviewed sessions';
    END IF;

    UPDATE event_session s
    SET event_id = p_keep,
        source_key = CASE
            WHEN EXISTS (SELECT 1 FROM event_session k WHERE k.event_id = p_keep AND k.source_key = s.source_key)
                THEN left(s.source_key, 140) || '-m' || s.id
            ELSE s.source_key END
    WHERE s.event_id = p_drop;

    -- Два источника привезли один и тот же сеанс: лишний удаляется, если с ним ничего не делали.
    DELETE FROM event_session d
    WHERE d.event_id = p_keep
      AND NOT session_has_activity(d.id)
      AND EXISTS (
          SELECT 1 FROM event_session k
          WHERE k.event_id = p_keep AND k.id <> d.id
            AND abs(extract(epoch FROM k.starts_at - d.starts_at)) <= 300
            AND (session_has_activity(k.id) OR k.id < d.id)
      );

    INSERT INTO event_reaction (user_id, event_id, kind, is_public, reacted_at)
    SELECT user_id, p_keep, kind, is_public, reacted_at FROM event_reaction WHERE event_id = p_drop
    ON CONFLICT (user_id, event_id) DO NOTHING;

    UPDATE event_feedback SET event_id = p_keep WHERE event_id = p_drop;

    INSERT INTO event_category (event_id, category_id)
    SELECT p_keep, category_id FROM event_category WHERE event_id = p_drop
    ON CONFLICT DO NOTHING;
    INSERT INTO event_tag (event_id, tag_id)
    SELECT p_keep, tag_id FROM event_tag WHERE event_id = p_drop
    ON CONFLICT DO NOTHING;

    -- Жалобы переходят на оставшееся событие; повторная открытая жалоба того же автора закрывается.
    UPDATE report r
    SET status = 'REVIEWED', reviewed_at = now()
    WHERE r.target_type = 'event' AND r.target_id = p_drop AND r.status = 'NEW'
      AND EXISTS (
          SELECT 1 FROM report o
          WHERE o.author_id = r.author_id AND o.target_type = 'event'
            AND o.target_id = p_keep AND o.status = 'NEW'
      );
    UPDATE report SET target_id = p_keep WHERE target_type = 'event' AND target_id = p_drop;

    UPDATE event_link SET event_id = p_keep WHERE event_id = p_drop;
    UPDATE event k
    SET place_id = coalesce(k.place_id, d.place_id)
    FROM event d
    WHERE k.id = p_keep AND d.id = p_drop;

    -- Пары с удаляемым событием пересчитаются при следующем поиске.
    DELETE FROM event_duplicate
    WHERE status = 'NEW' AND (event_a = p_drop OR event_b = p_drop)
      AND (event_a, event_b) <> (least(p_keep, p_drop), greatest(p_keep, p_drop));
    INSERT INTO event_duplicate (event_a, event_b, title_a, title_b, score, reason, status, resolved_at, resolved_by)
    VALUES (least(p_keep, p_drop), greatest(p_keep, p_drop),
            CASE WHEN p_keep < p_drop THEN title_keep ELSE title_drop END,
            CASE WHEN p_keep < p_drop THEN title_drop ELSE title_keep END,
            1, coalesce(p_reason, 'склеено'), 'MERGED', now(), p_by)
    ON CONFLICT (event_a, event_b) DO UPDATE
        SET status = 'MERGED', resolved_at = now(), resolved_by = EXCLUDED.resolved_by;

    DELETE FROM event WHERE id = p_drop;
    PERFORM refresh_event(p_keep);
END;
$$;

-- Уверенные пары склеиваются, сомнительные попадают в очередь модератора.
-- Цепочки «А похоже на Б, Б похоже на В» сходятся за несколько проходов.
CREATE OR REPLACE FUNCTION resolve_duplicates()
RETURNS TABLE (merged integer, queued integer)
LANGUAGE plpgsql
SET search_path FROM CURRENT
AS $$
DECLARE
    r record;
    keep_id bigint;
    drop_id bigint;
    merged_now integer;
    pass integer := 0;
    rows_added integer;
BEGIN
    merged := 0;
    queued := 0;
    LOOP
        pass := pass + 1;
        merged_now := 0;
        FOR r IN SELECT * FROM find_duplicate_pairs() ORDER BY confident DESC, score DESC, event_a, event_b LOOP
            CONTINUE WHEN NOT EXISTS (SELECT 1 FROM event WHERE id = r.event_a)
                       OR NOT EXISTS (SELECT 1 FROM event WHERE id = r.event_b);
            IF r.confident THEN
                -- Остаётся событие, с которым люди уже что-то делали, иначе более раннее.
                SELECT id INTO keep_id
                FROM event e
                WHERE e.id IN (r.event_a, r.event_b)
                ORDER BY (SELECT count(*) FROM event_reaction x WHERE x.event_id = e.id)
                       + (SELECT count(*) FROM event_intention i JOIN event_session s ON s.id = i.session_id
                          WHERE s.event_id = e.id) DESC,
                         e.id
                LIMIT 1;
                drop_id := CASE WHEN keep_id = r.event_a THEN r.event_b ELSE r.event_a END;
                BEGIN
                    PERFORM merge_events(keep_id, drop_id, NULL, 'автоматически: ' || r.reason);
                    merged := merged + 1;
                    merged_now := merged_now + 1;
                    CONTINUE;
                EXCEPTION WHEN raise_exception THEN
                    -- Например, у события есть отзывы с оценкой: решение остаётся за модератором.
                    NULL;
                END;
            END IF;
            INSERT INTO event_duplicate (event_a, event_b, title_a, title_b, score, reason)
            SELECT r.event_a, r.event_b, ea.title, eb.title, r.score, r.reason
            FROM event ea, event eb
            WHERE ea.id = r.event_a AND eb.id = r.event_b
            ON CONFLICT (event_a, event_b) DO NOTHING;
            GET DIAGNOSTICS rows_added = ROW_COUNT;
            queued := queued + rows_added;
        END LOOP;
        EXIT WHEN merged_now = 0 OR pass >= 10;
    END LOOP;
    RETURN NEXT;
END;
$$;

-- Очередь модератора: обе стороны пары с ближайшим сеансом, площадкой и источником.
CREATE OR REPLACE FUNCTION duplicate_queue()
RETURNS TABLE (
    id bigint, score numeric, reason text, created_at timestamptz,
    a_id bigint, a_title varchar, a_cover text, a_place varchar, a_starts timestamptz, a_source varchar,
    b_id bigint, b_title varchar, b_cover text, b_place varchar, b_starts timestamptz, b_source varchar
)
LANGUAGE sql STABLE
AS $$
    SELECT d.id, d.score, d.reason, d.created_at,
           a.id, a.title, a.cover_url, pa.name,
           (SELECT min(starts_at) FROM event_session WHERE event_id = a.id AND coalesce(ends_at, starts_at) > now()),
           sa.name,
           b.id, b.title, b.cover_url, pb.name,
           (SELECT min(starts_at) FROM event_session WHERE event_id = b.id AND coalesce(ends_at, starts_at) > now()),
           sb.name
    FROM event_duplicate d
    JOIN event a ON a.id = d.event_a
    JOIN event b ON b.id = d.event_b
    JOIN catalog_source sa ON sa.id = a.source_id
    JOIN catalog_source sb ON sb.id = b.source_id
    LEFT JOIN place pa ON pa.id = a.place_id
    LEFT JOIN place pb ON pb.id = b.place_id
    WHERE d.status = 'NEW'
    ORDER BY d.score DESC, d.id
$$;

