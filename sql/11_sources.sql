CREATE OR REPLACE FUNCTION mark_distinct(p_duplicate bigint, p_by bigint) RETURNS void
LANGUAGE plpgsql
SET search_path FROM CURRENT
AS $$
BEGIN
    UPDATE event_duplicate
    SET status = 'DISTINCT', resolved_at = now(), resolved_by = p_by
    WHERE id = p_duplicate AND status = 'NEW';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Duplicate pair is not pending';
    END IF;
END;
$$;
